let lang = localStorage.getItem('kb.lang') || 'fa';
if (!I18N[lang]) lang = 'fa';

function t(key) {
  let c = I18N[lang];
  for (const p of key.split('.')) { if (!c) return key; c = c[p]; }
  return c === undefined ? key : c;
}

function L(obj) { return obj && obj[lang] !== undefined ? obj[lang] : ''; }

function num(n) {
  return n.toLocaleString(lang === 'fa' ? 'fa-IR' : 'en-US');
}

function money(n) {
  return num(n) + ' تومان';
}

function toggleLang() {
  lang = lang === 'fa' ? 'en' : 'fa';
  localStorage.setItem('kb.lang', lang);
  document.documentElement.setAttribute('dir', I18N[lang].dir);
  document.documentElement.setAttribute('lang', lang);
  location.reload();
}

function initLang() {
  document.documentElement.setAttribute('dir', I18N[lang].dir);
  document.documentElement.setAttribute('lang', lang);
}
